/**
 * Desktop shortcuts for מקלדת, taken from shrtcts.click for the design apps.
 * The English face is the US key. The Hebrew face is the character on that
 * same key in the standard Hebrew layout (K is ל, not קיי).
 * ponytail: Windows is a modifier swap (cmd→ctrl, and cmd→alt when ctrl is
 * already in the chord). PowerPoint group is the explicit exception.
 * Mouse, fn, Home, and End chords are omitted. US layout; versions differ.
 */

const swapModifiers = (keys) => {
  const hasCtrl = keys.includes('ctrl');
  return keys.map((key) => {
    if (key === 'cmd') return hasCtrl ? 'alt' : 'ctrl';
    if (key === 'opt') return 'alt';
    return key;
  });
};

const shortcut = (id, app, category, label, mac, win = swapModifiers(mac)) => ({
  id,
  app,
  category,
  label,
  mac,
  win,
});

