const swapModifiers = (keys) =>
  keys.map((key) => (key === 'cmd' ? 'ctrl' : key === 'opt' ? 'alt' : key));

const shortcut = (id, app, category, label, mac, win = swapModifiers(mac)) => ({
  id,
  app,
  category,
  label,
  mac,
  win,
});

